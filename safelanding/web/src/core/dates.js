// Dates calendaires en UTC, format strict AAAA-MM-JJ (aucune dépendance au fuseau local).
export function parseDate(s) {
  if (typeof s !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(s)) return null;
  const [y, m, d] = s.split('-').map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d));
  return dt.getUTCFullYear() === y && dt.getUTCMonth() === m - 1 && dt.getUTCDate() === d ? dt : null;
}
export const toISO = (d) => d.toISOString().slice(0, 10);
export const addDays = (d, n) => new Date(d.getTime() + n * 864e5);
export function addMonths(d, n) {
  const y = d.getUTCFullYear(), m = d.getUTCMonth() + n, day = d.getUTCDate();
  const last = new Date(Date.UTC(y, m + 1, 0)).getUTCDate();
  return new Date(Date.UTC(y, m, Math.min(day, last)));
}
export const diffDays = (a, b) => Math.round((b.getTime() - a.getTime()) / 864e5); // b - a
export const todayUTC = (now = new Date()) => parseDate(toISO(now));
export function fmt(d) { return d ? toISO(d) : ''; }
